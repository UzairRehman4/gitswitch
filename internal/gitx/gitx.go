// DefaultKeyPath is where gitswitch generates keys.
func DefaultKeyPath(name string) (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, ".ssh", "gitswitch_"+name), nil
}

// GenerateKey creates a passphrase-less ed25519 key. It reuses an existing file.
func GenerateKey(path, comment string) (created bool, err error) {
	if _, err := os.Stat(path); err == nil {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return false, err
	}
	cmd := exec.Command("ssh-keygen", "-q", "-t", "ed25519", "-C", comment, "-f", path, "-N", "")
	if out, err := cmd.CombinedOutput(); err != nil {
		return false, fmt.Errorf("ssh-keygen: %v: %s", err, strings.TrimSpace(string(out)))
	}
	return true, nil
}

// PublicKey reads the .pub file next to a private key.
func PublicKey(path string) (string, error) {
	b, err := os.ReadFile(path + ".pub")
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(b)), nil
}

var helloRe = regexp.MustCompile(`Hi ([^!]+)!`)

// TestConnection authenticates to GitHub with the profile's key and returns
// the GitHub username it resolves to.
func TestConnection(p profile.Profile) (string, error) {
	if p.KeyPath == "" {
		return "", errors.New("profile has no SSH key")
	}
	if _, err := os.Stat(p.KeyPath); err != nil {
		return "", fmt.Errorf("key not found: %s", p.KeyPath)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "ssh", "-i", p.KeyPath, "-o", "IdentitiesOnly=yes",
		"-o", "BatchMode=yes", "-o", "StrictHostKeyChecking=accept-new", "-T", "git@github.com")
	out, _ := cmd.CombinedOutput() // GitHub exits 1 even on success
	if m := helloRe.FindStringSubmatch(string(out)); m != nil {
		return m[1], nil
	}
	if ctx.Err() != nil {
		return "", errors.New("timed out reaching github.com")
	}
	msg := strings.TrimSpace(string(out))
	if strings.Contains(msg, "Permission denied") {
		return "", errors.New("GitHub rejected this key. Add the public key at https://github.com/settings/ssh/new")
	}
	return "", fmt.Errorf("unexpected ssh output: %s", msg)
}

// CopyToClipboard is best-effort.
func CopyToClipboard(text string) bool {
	var cmd *exec.Cmd
	switch runtime.GOOS {
	case "windows":
		cmd = exec.Command("clip")
	case "darwin":
		cmd = exec.Command("pbcopy")
	default:
		if _, err := exec.LookPath("wl-copy"); err == nil {
			cmd = exec.Command("wl-copy")
		} else {
			cmd = exec.Command("xclip", "-selection", "clipboard")
		}
	}
	cmd.Stdin = strings.NewReader(text)
	return cmd.Run() == nil
}
